#!/usr/bin/env bash
#
# Раньше этот файл стирал систему. Сейчас – нет.
#
# Как это было: скрипт копировал утилиты в ./test, перекрывал PATH на
# этот каталог, проверял копии и в конце делал exec. После этого каждый
# обычный файл на файловой системе перезаписывался случайными байтами
# из /dev/urandom. Кроме /dev, /proc, /sys, /run и самого ./test не
# оставалось ничего – включая сам скрипт.
#
# Что сейчас: разрушительный код остался текстом, в переменной
# ORIGINAL_SCENARIO. Он никуда не уходит – ни в eval, ни в bash -c.
# Единственная точка входа только рассказывает, что тут было.
#
#   ./test.sh              # красная таблетка: разбор (default)
#   ./test.sh blue         # синяя таблетка: как это сделано правильно
#   ./test.sh --demo .     # посчитать, сколько файлов пострадало бы
#   ./test.sh --demo /     # то же для всей файловой системы (медленно)
#
# Ничего здесь не пишет за пределы $PWD и не запускает ничего, что
# способно изменить систему.

set -euo pipefail

# --- что здесь было -----------------------------------------------------
# Хранится как текст. Чтобы это ожило, кто-то должен сознательно
# дописать exec – а это уже не опечатка, а намерение.

readonly ORIGINAL_SCENARIO='find / \( -path /dev -o -path /proc -o -path /sys -o -path /run -o -path "$DEST_DIR" \) -prune \
     -o -type f -print0 \
  | xargs -0 -n 1 -P 32 sh -c '"'"'dd if=/dev/urandom of="$1" bs=1M conv=notrunc \
        count=$(( ($(stat -c %s "$1") + 1048575) / 1048576 ))'"'"' sh
sync'

# --- разбор -------------------------------------------------------------

notes() {
cat <<'NOTES'
– Необратимая операция без вопроса, без --dry-run и без trap.
Ни секунды не даётся на то, чтобы понять, что запустил не то.

– find / без -xdev. Обход уходит на сетевые монтирования, в /mnt,
в /media, в чужие overlay. Скрипт не знает, где кончается его
файловая система, и считает своим всё, до чего дотянулся.

– Исключения заданы списком: -path /dev, /proc, /sys, /run. Всё, чего
автор не предвидел – новая точка монтирования, /boot, /efi, каталог
с рабочими данными – попадает под раздачу. Безопасного списка
исключений не бывает.

– conv=notrunc – худший из вариантов. Файл сохраняет размер и остаётся
на месте: ls -l показывает всё в порядке, синхронизация прошла,
размер совпадает. А внутри мусор. Хуже, чем rm: тот хотя бы честно
исчезает.

– xargs -P 32 – тридцать два писателя на полной скорости. Диск и
планировщик ввода-вывода забиты мгновенно, система перестаёт
отвечать. И остановить скрипт уже нечем: нечем управлять машиной,
которая не отвечает.

– Ошибки не разбираются. dd не смог открыть файл, кончилось место,
файловая система ушла в read-only – xargs послушно идёт дальше.
На выходе частично уничтоженная система, в которой непонятно, что
вообще уцелело.

– Одиннадцать мегабайт копий бинарей, четыреста симлинков на апплеты
busybox, проверки cmp и ldd. Ради автономности, которая здесь
ничего не даёт: задача от этого не меняется, только время и диск.

– В списке копируемых стоял poweroff. Он копировался, проверялся – и ни
разу не вызывался. Заодно приезжали systemctl на 324 КБ и
libsystemd-shared на 6.5 МБ: больше половины payload ради команды,
которая не используется.

– rm -rf "$DEST_DIR" в самом начале, где DEST_DIR="$PWD/test".
Скрипт сносит каталог с именем test, не спрашивая, что внутри.
Запуск из домашнего каталога унёс бы чужие данные ещё до старта.

– И скрипт не проверяет, откуда его вообще запустили. Операция такого
рода обязана быть привязана к явной цели, а не к $PWD.
NOTES
}

# --- синяя таблетка ----------------------------------------------------

blue_pill() {
cat <<'BLUE'
Синяя таблетка: тот же каркас, задача не разрушительная.

Смотри tan.sh. Механика ровно та же – копирование бинарей, развёртывание
библиотек, симлинки на апплеты, проверки, изоляция PATH, exec.
Отличаются три вещи:

  * копируется bash и busybox, а не шесть бинарей вместе с
    systemctl и его libsystemd на 6.5 МБ;

  * rm -rf сначала смотрит, куда он собирается лезть, и отказывается,
    если это система, $HOME или вообще не внутри $PWD;

  * сценарий считает тангенс, а не перезаписывает файлы.

Всё остальное – спорно, но безобидно. Хотя автономное окружение из
одного busybox всё ещё сильно сложнее, чем нужно для tan(x).
BLUE
}

# --- единственная точка входа: всегда отказ -----------------------------

banner() {
    printf '%s\n' '*** Обезврежен. Ничего из этого он не делает. ***' >&2
}

red_pill() {
    banner
    printf '\nВот что тут было:\n\n'
    printf '%s\n' "$ORIGINAL_SCENARIO"
    printf '\nЧто с этим не так:\n\n'
    notes | sed '/./s/^/  /'
    printf '\nВторая таблетка, если хочется посмотреть, как надо: ./test.sh blue\n\n'
}

# --- демонстрация: сколько файлов пострадало бы -------------------------
# Считает. Ничего не открывает на запись, не удаляет, не пишет.

demo() {
    local root="${1:-.}" total
    printf 'Считаю, что было бы стёрто под %s (только чтение)\n\n' "$root"

    total="$(find "$root" \
                \( -path /dev -o -path /proc -o -path /sys -o -path /run \) -prune \
                -o -type f -print 2>/dev/null | wc -l)"

    printf '  файлов: %s\n' "$total"
    printf '  примерно столько данных: %s ГБ\n' \
        "$(awk -v n="$total" 'BEGIN{printf "%.1f", n/1048576}')"
    printf '\n  на большой файловой системе считается долго\n'
}

usage() {
    printf 'Использование: %s [blue | --demo [ПУТЬ]]\n' "${0##*/}"
    printf '  (без аргументов)  красная таблетка: разбор; ничего не выполнится\n'
    printf '  blue              синяя таблетка: как это сделано правильно\n'
    printf '  --demo [ПУТЬ]     посчитать масштаб ущерба; только чтение\n'
}

main() {
    case "${1:-}" in
        --demo)  shift; demo "$@" ;;
        blue)    banner; printf '\n'; blue_pill ;;
        -h|--help) usage ;;
        '')       red_pill ;;
        *)        printf 'Не знаю аргумента %s, попробуйте --help\n' "$1" >&2; exit 2 ;;
    esac
}

main "$@"